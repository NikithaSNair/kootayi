export function isValidAadhaar(num: string) {
  const s = num.replace(/\s/g, "");
  if (!/^[2-9]\d{11}$/.test(s)) return false;
  let c = 0;
  const digits = s.split("").reverse().map(Number);
  for (let i = 0; i < digits.length; i++) c = d[c][p[i % 8][digits[i]]];
  return c === 0;
}
